
#include <UserWindow.hpp>
//ROOT headers
#include <TError.h> 

//__________________________________________________________________________________________________________________________
UserWindow::UserWindow(const std::string& name, const std::function<void(UserApp*)>& app_draw_function)
    : fName{name}, fDrawAppFunction{app_draw_function}
{   
}
//__________________________________________________________________________________________________________________________
void UserWindow::WindowClosed()
{
    //noop  
}
//__________________________________________________________________________________________________________________________
void UserWindow::DrawWindow()
{
    if (IsActive()) {
        Warning(__func__, "<UserWindow: %s>: 'DrawWindow' called while app is already active", GetName().c_str()); 
        return; 
    }
    fApp = new UserApp(this, gClient->GetRoot(), fWidth, fHeight, fDrawAppFunction); 
}
//__________________________________________________________________________________________________________________________
bool UserWindow::IsActive() const { return fApp != nullptr; }
//__________________________________________________________________________________________________________________________
UserWindow::~UserWindow() {
    
    //close & delete the app, if it's open 
    if (IsActive()) { fApp->CloseWindow(); }
}
