#include <PrivateMessenger.hpp>
#include <EventDisplayKernel.hpp>

//__________________________________________________________________________________________________________________________
void PrivateMessenger::SetCanvas(TCanvas* canv)
{
    auto& kernel = EventDisplayKernel::Instance(); 
    kernel.fCurrentCanvas = canv; 
}
//__________________________________________________________________________________________________________________________
void PrivateMessenger::SetUserWindow(UserWindow* window)
{
    auto& kernel = EventDisplayKernel::Instance(); 
    kernel.fCurrentUserWindow = window; 
}
//__________________________________________________________________________________________________________________________
void PrivateMessenger::SetObjDrawFunctionName(std::string name)
{
    auto& kernel = EventDisplayKernel::Instance(); 
    kernel.fCurrentObjDrawFunctionName = name; 
}
//__________________________________________________________________________________________________________________________
void PrivateMessenger::SetAppDrawFunctionName(std::string name)
{
    auto& kernel = EventDisplayKernel::Instance(); 
    kernel.fCurrentAppDrawFunctionName = name; 
}
